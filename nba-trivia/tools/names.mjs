// Compiles the Arabic names (data/names-ar/*.tsv, one "English<TAB>Arabic" per
// line) and the team names in i18n/ar.json into data/names-ar.js, which the
// question builder and the weekly update read.
//   node tools/names.mjs
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const { TEAMS } = await import(join(ROOT, 'data', 'teams.js'));
const ar = JSON.parse(readFileSync(join(ROOT, 'i18n', 'ar.json'), 'utf8'));
const names = {}, problems = [];
const put = (en, a, where) => {
  if (!en || !a) return problems.push(`${where}: empty entry`);
  if (/[A-Za-z]/.test(a.replace(/\b(NBA|BAA|UCLA|UNLV|USC|LSU|UTEP|SMU|TCU|BYU|VCU|UAB|UCF|UNC|FC|KK|BC|CB|SC|II|III|IV|HS|\.com)\b/g, ''))) problems.push(`${where}: Latin letters left in "${a}" (${en})`);
  if (names[en] && names[en] !== a) problems.push(`${where}: "${en}" is "${names[en]}" elsewhere, "${a}" here`);
  names[en] = a;
};
// the 30 teams: full name, nickname, city
for (const t of TEAMS) {
  const [city, nick] = ar.team_names[t.id];
  put(`${t.city} ${t.name}`, `${city} ${nick}`, 'ar.json'); put(t.name, nick, 'ar.json'); put(t.city, city, 'ar.json');
}
const dir = join(ROOT, 'data', 'names-ar');
for (const f of readdirSync(dir).filter(f => f.endsWith('.tsv')).sort((a, b) => parseInt(a) - parseInt(b))) {
  readFileSync(join(dir, f), 'utf8').split('\n').forEach((line, i) => {
    if (!line.trim() || line.startsWith('#')) return;
    const [en, a, extra] = line.split('\t');
    if (extra !== undefined || a === undefined) return problems.push(`${f}:${i + 1}: expected two columns`);
    put(en.trim(), a.trim(), `${f}:${i + 1}`);
  });
}
const body = Object.entries(names).sort(([a], [b]) => a.localeCompare(b)).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n');
writeFileSync(join(ROOT, 'data', 'names-ar.js'),
  `// Arabic spellings of names (players, coaches, teams, colleges, arenas, countries).\n// Generated by tools/names.mjs from data/names-ar/*.tsv and i18n/ar.json — edit those, not this file.\nexport const NAMES = {\n${body}\n};\n`);
console.log('names', Object.keys(names).length, problems.length ? '\nPROBLEMS\n  ' + problems.join('\n  ') : '· no problems');
